create policy "Atualizar imagens da loja" on storage.objects for update
using (bucket_id = 'loja-tetelestai');

drop policy if exists "Excluir imagens da loja" on storage.objects;
create policy "Excluir imagens da loja" on storage.objects for delete
using (bucket_id = 'loja-tetelestai');
